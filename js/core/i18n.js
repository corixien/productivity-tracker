const SUPPORTED = Object.keys(translations);
const STORAGE_KEY = 'lang';
let currentLang = detectLanguage();
const listeners = new Set();

function detectLanguage() {
    try {
        const stored = localStorage.getItem(STORAGE_KEY);
        if (SUPPORTED.includes(stored)) return stored;
    } catch (error) {
        // storage unavailable: fall through
    }
    return (navigator.language || 'en').toLowerCase().startsWith('de') ? 'de' : 'en';
}

function t(key, params) {
    const value = translations[currentLang][key] ?? translations.en[key] ?? key;
    if (!params) return value;
    return value.replace(/\{(\w+)\}/g, (match, name) => (params[name] !== undefined ? params[name] : match));
}

function translateDom(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}

function setLanguage(lang) {
    if (!SUPPORTED.includes(lang)) return;
    currentLang = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (error) { /* ignore */ }
    document.documentElement.lang = lang;
    translateDom();
    document.querySelectorAll('select[data-lang-select], #language-select, #auth-language').forEach((el) => { el.value = lang; });
    listeners.forEach((fn) => fn(lang));
}

function onLanguageChange(fn) {
    listeners.add(fn);
    return () => listeners.delete(fn);
}

const getCurrentLang = () => currentLang;
const locale = () => (currentLang === 'de' ? 'de-DE' : 'en-US');

export { t, setLanguage, getCurrentLang, onLanguageChange, translateDom, locale, translations };
